/* pdf.js — DiaryWell report builder.
   Renders an HTML "doctor report" into a container that prints cleanly
   via the print stylesheet. No external libraries.
*/
(function (global) {
  'use strict';

  function buildReport(opts) {
    var entries = opts.entries || [];
    var fromDate = opts.fromDate;
    var toDate = opts.toDate;
    var name = (opts.name || '').trim();
    var tags = opts.tags || [];
    var generatedAt = opts.now || new Date();

    var tagById = {};
    tags.forEach(function (t) { tagById[t.id] = t; });

    var inRange = entries.filter(function (e) {
      return e.date >= fromDate && e.date <= toDate;
    });

    var stats = computeStats(inRange);
    var symptomTop = topByCount(inRange, 'symptoms', tagById, 5);
    var triggerTop = topByCount(inRange, 'triggers', tagById, 5);

    var html = '';
    html += '<div class="rep-head">';
    html += '  <div>';
    html += '    <h2 style="margin:0">DiaryWell Symptom & Mood Report</h2>';
    if (name) html += '    <p style="margin:4px 0 0">For: ' + escape(name) + '</p>';
    html += '    <p class="muted small" style="margin:2px 0 0">Period: ' + escape(fromDate) + ' to ' + escape(toDate) + '</p>';
    html += '  </div>';
    html += '  <p class="muted small" style="margin:0">Generated ' + escape(formatDate(generatedAt)) + '</p>';
    html += '</div>';

    html += '<h2>Summary</h2>';
    html += '<div class="rep-stats">';
    html += stat('Days logged', stats.daysLogged + ' / ' + stats.totalDays);
    html += stat('Average pain', stats.avgPain != null ? stats.avgPain.toFixed(1) + ' / 10' : '—');
    html += stat('Average mood', stats.avgMood != null ? stats.avgMood.toFixed(1) + ' / 5' : '—');
    html += stat('Average sleep', stats.avgSleep != null ? stats.avgSleep.toFixed(1) + ' h' : '—');
    html += stat('Flare days (pain ≥ 7)', String(stats.flareDays));
    html += stat('Best-mood days (mood ≥ 4)', String(stats.goodMoodDays));
    html += '</div>';

    if (stats.daysLogged === 0) {
      html += '<p class="muted">No entries in this range. Try widening the dates.</p>';
    }

    html += '<h2>Top symptoms</h2>';
    html += renderRanked(symptomTop, 'No symptoms logged in this range.');

    html += '<h2>Top triggers</h2>';
    html += renderRanked(triggerTop, 'No triggers logged in this range.');

    html += '<h2>Calendar (period overview)</h2>';
    html += renderHeatmapTable(inRange, fromDate, toDate);

    html += '<h2>Daily log (most recent 30 days)</h2>';
    var recent = inRange.slice(-30).reverse();
    html += renderEntryTable(recent, tagById);

    html += '<div class="rep-footer">';
    html += '<p><strong>How to read this report:</strong> Pain is on a 0–10 scale. Mood is on a 1–5 scale where 5 is best. ';
    html += 'Sleep is hours per night reported by the patient. Flare days are pain ≥ 7.</p>';
    html += '<p><strong>Disclaimer:</strong> DiaryWell is a self-tracking tool. It is not a diagnostic device and does not provide medical advice. ';
    html += 'Please discuss these patterns with your clinician before changing treatment.</p>';
    html += '<p><em>Generated by DiaryWell. Your data stayed on your device — nothing was uploaded.</em></p>';
    html += '</div>';

    return html;
  }

  function computeStats(entries) {
    var totalDays = entries.length === 0 ? 0 : daysBetween(entries[0].date, entries[entries.length - 1].date) + 1;
    if (totalDays === 0) totalDays = 1;
    var pains = [], moods = [], sleeps = [];
    var flare = 0, good = 0;
    entries.forEach(function (e) {
      if (e.pain != null) { pains.push(e.pain); if (e.pain >= 7) flare++; }
      if (e.mood != null) { moods.push(e.mood); if (e.mood >= 4) good++; }
      if (e.sleepHours != null && !isNaN(e.sleepHours)) sleeps.push(e.sleepHours);
    });
    return {
      daysLogged: entries.length,
      totalDays: totalDays,
      avgPain: pains.length ? avg(pains) : null,
      avgMood: moods.length ? avg(moods) : null,
      avgSleep: sleeps.length ? avg(sleeps) : null,
      flareDays: flare,
      goodMoodDays: good
    };
  }

  function avg(a) { return a.reduce(function (x, y) { return x + y; }, 0) / a.length; }

  function topByCount(entries, key, tagById, n) {
    var counts = {};
    entries.forEach(function (e) {
      (e[key] || []).forEach(function (id) {
        counts[id] = (counts[id] || 0) + 1;
      });
    });
    var arr = Object.keys(counts).map(function (id) {
      var t = tagById[id];
      return {
        id: id,
        name: t ? t.name : id,
        count: counts[id]
      };
    });
    arr.sort(function (a, b) { return b.count - a.count; });
    return arr.slice(0, n);
  }

  function renderRanked(list, emptyText) {
    if (!list || list.length === 0) {
      return '<p class="muted">' + escape(emptyText) + '</p>';
    }
    var max = list[0].count || 1;
    var html = '<table><thead><tr><th>Item</th><th style="width:60px">Days</th><th>Frequency</th></tr></thead><tbody>';
    list.forEach(function (it) {
      var pct = Math.round((it.count / max) * 100);
      html += '<tr><td>' + escape(it.name) + '</td><td>' + it.count + '</td>';
      html += '<td><div style="background:#eee;border-radius:3px;height:8px;width:120px;display:inline-block;overflow:hidden">';
      html += '<div style="background:#7C3AED;height:100%;width:' + pct + '%"></div></div></td></tr>';
    });
    html += '</tbody></table>';
    return html;
  }

  function renderEntryTable(entries, tagById) {
    if (!entries || entries.length === 0) {
      return '<p class="muted">No entries.</p>';
    }
    var html = '<table><thead><tr>';
    html += '<th>Date</th><th>Mood</th><th>Pain</th><th>Energy</th><th>Sleep</th><th>Symptoms</th><th>Triggers</th><th>Notes</th>';
    html += '</tr></thead><tbody>';
    entries.forEach(function (e) {
      var syms = (e.symptoms || []).map(function (id) { return tagById[id] ? tagById[id].name : id; }).join(', ');
      var trigs = (e.triggers || []).map(function (id) { return tagById[id] ? tagById[id].name : id; }).join(', ');
      html += '<tr>';
      html += '<td>' + escape(e.date) + '</td>';
      html += '<td>' + (e.mood != null ? e.mood : '—') + '</td>';
      html += '<td>' + (e.pain != null ? e.pain : '—') + '</td>';
      html += '<td>' + (e.energy != null ? e.energy : '—') + '</td>';
      html += '<td>' + (e.sleepHours != null ? e.sleepHours + 'h' : '—') + (e.sleepQuality ? ' (Q' + e.sleepQuality + ')' : '') + '</td>';
      html += '<td>' + escape(syms || '—') + '</td>';
      html += '<td>' + escape(trigs || '—') + '</td>';
      html += '<td>' + escape(e.note || '') + '</td>';
      html += '</tr>';
    });
    html += '</tbody></table>';
    return html;
  }

  function renderHeatmapTable(entries, fromDate, toDate) {
    // Build a small SVG heatmap for the report.
    var map = {};
    entries.forEach(function (e) { map[e.date] = e; });
    var start = parseISO(fromDate);
    var end = parseISO(toDate);
    var days = Math.max(1, Math.round((end - start) / 86400000) + 1);
    var weeks = Math.ceil(days / 7);
    var cell = 14, gap = 2;
    var w = weeks * (cell + gap) + 30;
    var h = 7 * (cell + gap) + 16;
    var palette = ['#ECECF3','#D7CBF5','#B79CEC','#946EE0','#7245CB','#4F2DA1'];

    // Align start to Monday
    var firstMon = new Date(start);
    firstMon.setDate(firstMon.getDate() - mondayBased(firstMon.getDay()));

    var svg = '<svg class="heatmap-print" xmlns="http://www.w3.org/2000/svg" width="' + w + '" height="' + h + '" viewBox="0 0 ' + w + ' ' + h + '" role="img" aria-label="Calendar heatmap">';
    svg += '<style>text{font-family:sans-serif;font-size:9px;fill:#666}</style>';
    var labels = ['Mo','','We','','Fr','',''];
    for (var r = 0; r < 7; r++) {
      if (labels[r]) {
        svg += '<text x="0" y="' + (r * (cell + gap) + cell - 2) + '">' + labels[r] + '</text>';
      }
    }
    var totalDays = weeks * 7;
    for (var i = 0; i < totalDays; i++) {
      var d = new Date(firstMon);
      d.setDate(firstMon.getDate() + i);
      if (d < start || d > end) continue;
      var col = Math.floor(i / 7);
      var row = i % 7;
      var key = isoDate(d);
      var e = map[key];
      var color = palette[0];
      if (e) {
        var sc = scoreOf(e);
        var bucket = Math.min(5, Math.max(1, Math.ceil(sc / 2)));
        color = palette[bucket];
      }
      var x = 20 + col * (cell + gap);
      var y = row * (cell + gap);
      svg += '<rect x="' + x + '" y="' + y + '" width="' + cell + '" height="' + cell + '" rx="2" fill="' + color + '"/>';
    }
    svg += '</svg>';
    return svg + '<p class="muted small" style="margin-top:4px">Darker = tougher day (higher pain / lower mood).</p>';
  }

  function scoreOf(e) {
    var parts = [];
    if (e.mood) parts.push((5 - Math.max(1, Math.min(5, e.mood))) * 2);
    if (e.pain != null) parts.push(Math.max(0, Math.min(10, e.pain)));
    if (parts.length === 0) return 0;
    return parts.reduce(function (a, b) { return a + b; }, 0) / parts.length;
  }

  function stat(label, value) {
    return '<div class="stat"><div class="stat-num">' + escape(value) + '</div><div class="stat-label">' + escape(label) + '</div></div>';
  }

  function escape(s) {
    if (s == null) return '';
    return String(s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  function parseISO(s) {
    var p = String(s).split('-');
    return new Date(parseInt(p[0], 10), parseInt(p[1], 10) - 1, parseInt(p[2], 10));
  }
  function isoDate(d) {
    return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
  }
  function mondayBased(jsDay) { return (jsDay + 6) % 7; }
  function daysBetween(a, b) {
    return Math.round((parseISO(b) - parseISO(a)) / 86400000);
  }
  function formatDate(d) {
    return d.toISOString().slice(0, 16).replace('T', ' ');
  }

  global.DiaryReport = {
    build: buildReport
  };
})(window);
